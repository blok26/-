/**
 * Filter words by selected difficulty, or get random mixed selection
 */
export function getRandomWord(difficulty: 'easy' | 'medium' | 'mixed' = 'mixed', excludeIds: string[] = []): ArabicWord {
  let pool = ARABIC_WORDS;
  if (difficulty === 'easy') {
    pool = ARABIC_WORDS.filter((w) => w.difficulty === 'easy');
  } else if (difficulty === 'medium') {
    pool = ARABIC_WORDS.filter((w) => w.difficulty === 'medium' || w.difficulty === 'easy');
  }

  // Filter out recently used words if possible
  const available = pool.filter((w) => !excludeIds.includes(w.id));
  const finalPool = available.length > 0 ? available : pool;

  const randomIndex = Math.floor(Math.random() * finalPool.length);
  return finalPool[randomIndex];
}
